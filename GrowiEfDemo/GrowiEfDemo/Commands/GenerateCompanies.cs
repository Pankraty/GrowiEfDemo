    public string GenerateName()
    {
        int pattern = _faker.Random.Int(1, 100);
        string nameBody;

        if (pattern <= 55)
        {
            // ПАТТЕРН 1: Прилагательное + Существительное (самый частый для "странных" названий)
            // "Коварный Крокодил", "Вишневый Металлопрокат"
            string adj = GetMixedCaseWord(_faker.PickRandom(_adjectives));
            string noun = GetMixedCaseWord(_faker.PickRandom(_nouns));
            
            // Иногда только существительное
            if (_faker.Random.Bool(0.3f))
            {
                nameBody = noun;
            }
            else
            {
                nameBody = $"{adj} {noun}";
            }

            // Добавляем суффикс с вероятностью 40%
            if (_faker.Random.Bool(0.4f))
            {
                var suffix = _faker.PickRandom(_nameSuffixes);
                if (!string.IsNullOrEmpty(suffix))
                {
                    nameBody = $"{nameBody} {GetMixedCaseWord(suffix)}";
                }
            }

            // Формируем с кавычками
            var inner = _faker.PickRandom(_innerPrefixes);
            if (!string.IsNullOrEmpty(inner))
            {
                nameBody = $"{inner} \"{nameBody}\"";
            }
            else
            {
                nameBody = $"\"{nameBody}\"";
            }
            
            // Добавляем число для уникальности (как "Альфа-77")
            if (_faker.Random.Bool(0.15f))
            {
                // Вставляем число перед закрывающей кавычкой или после названия
                nameBody = nameBody.Replace("\"", $"-{_faker.Random.Number(1, 999)}\"");
            }
        }
        else if (pattern <= 80)
        {
            // ПАТТЕРН 2: Административные и длинные названия
            var adminType = _faker.PickRandom(_adminTypes);
            var region = _faker.PickRandom(_regions);
            var geoName = _faker.Address.City();
            nameBody = $"{adminType} {geoName} {region}";
        }
        else if (pattern <= 90)
        {
            // ПАТТЕРН 3: Школы и учреждения
            var schoolType = _faker.PickRandom(_schoolTypes);
            var village = _faker.Address.City();
            var regionShort = _faker.PickRandom(new[] { "РБ", "РТ", "КО", "РО", "МО", "ЛО" });
            nameBody = $"{schoolType} с. {village} МР {regionShort}";
        }
        else
        {
            // ПАТТЕРН 4: Разные формы (ГАУ, Фонды)
            if (_faker.Random.Bool())
            {
                var abbr = _faker.PickRandom(new[] { "ГАУ", "ГКУ", "МУП", "Фонд", "Центр", "Ассоциация" });
                var regionShort = _faker.PickRandom(new[] { "РД", "РБ", "МСК", "СПБ", "НСК" });
                var shortName = _faker.PickRandom(_nameWords).ToUpper();
                nameBody = $"{abbr} {regionShort} \"{shortName}\"";
            }
            else
            {
                nameBody = GetMixedCaseWord(_faker.PickRandom(_nameWords));
                if (_faker.Random.Bool(0.5f))
                {
                    nameBody = $"\"{nameBody}\"";
                }
            }
        }

        string opf = _faker.PickRandom(_opfs);

        if (opf == "Администрация" || opf == "Совет" || opf == "Управление" || opf == "Фонд" || opf == "Ассоциация")
        {
            return $"{opf} {nameBody}".Trim();
        }

        if (opf.StartsWith("М") || opf.StartsWith("Г")) 
        {
             return $"{opf} {nameBody}".Trim();
        }

        if (nameBody.Contains("\""))
        {
            return $"{opf} {nameBody}";
        }

        return $"{opf} {nameBody}".Trim();
    }

    // Простая эвристика: если слово заканчивается на типичные суффиксы прилагательных
    private static bool IsAdjectiveLike(string word)
    {
        if (string.IsNullOrEmpty(word)) return false;
        string lower = word.ToLower();
        return lower.EndsWith("ый") || lower.EndsWith("ий") || lower.EndsWith("ой") ||
               lower.EndsWith("ный") || lower.EndsWith("ский") || lower.EndsWith("ной") ||
               lower.EndsWith("тый") || lower.EndsWith("ший") || lower.EndsWith("чий") ||
               lower.EndsWith("щий") || lower.EndsWith("нный") || lower.EndsWith("енный");
    }

    private string GetMixedCaseWord(string word)
    {
        if (string.IsNullOrEmpty(word)) return word;

        // Если слово целиком в списке важных, возвращаем как есть (с заглавной)
        if (_capsWords.Contains(word))
        {
            // Находим правильное написание в списке (регистрозависимо)
            return _capsWords.FirstOrDefault(w => w.Equals(word, StringComparison.OrdinalIgnoreCase)) ?? word;
        }

        // Если составное через дефис
        if (word.Contains("-"))
        {
            var parts = word.Split('-');
            var processedParts = parts.Select(GetMixedCaseWord);
            return string.Join("-", processedParts);
        }

        return char.ToUpper(word[0]) + word.Substring(1).ToLower();
    }


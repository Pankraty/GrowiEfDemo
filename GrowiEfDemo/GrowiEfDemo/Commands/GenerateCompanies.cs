using Bogus;
using FastEndpoints;
namespace GrowiEfDemo.Commands;

public class GenerateCompanies
{
    public record Request(int Count);

    public record Response(int Count);

    public class Handler(DemoDbContext dbContext) : Endpoint<Request, Response>
    {
        private readonly RealisticCompanyGenerator _generator = new ();

        public override void Configure()
        {
            Post("/companies/generate");
            AllowAnonymous();
        }

        public override async Task HandleAsync(Request request, CancellationToken ct)
        {
            var count = request.Count; 
            var portionSize = 100;
            if (portionSize > count)
                portionSize = count;

            while (count > 0)
            {
                for (int i = 0; i < portionSize; i++)
                {
                    var company = _generator.Generate();
                    dbContext.Companies.Add(company);
                }
                await dbContext.SaveChangesAsync(ct);
                dbContext.ChangeTracker.Clear();
                count -= portionSize;
            }
                        
            await Send.ResponseAsync(new Response(request.Count), cancellation: ct);
        }
    }
}

